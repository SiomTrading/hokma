"""Volatility surface. Rows FT-038, FT-039 and FT-040."""
import math

import numpy as np
import pytest

from hokma.quant.errors import BadInput
from hokma.quant.options import _common as c
from hokma.quant.options import _lib, surface

from .conftest import assert_empty, call, piece_ids

P0 = {"a": 0.002, "b": 0.03, "rho": -0.6, "m": 0.01, "sigma": 0.12}


def test_svi_recovers_known_parameters_FT_038():
    k = np.linspace(-0.3, 0.3, 25)
    t = 0.5
    iv = np.sqrt(np.asarray(surface.total_variance(k, P0)) / t)
    res = call("options.svi", log_moneyness=k.tolist(), implied_vol=iv.tolist(), time_to_expiration=t)
    # hand value: smile generated by known raw parameters is fitted back to them
    for key, value in P0.items():
        assert res.value["params"][key] == pytest.approx(value, abs=1.5e-3), key
    assert res.value["rmse_iv"] < 1e-5 and res.value["butterfly_free"] and res.value["wings_ok"]
    assert res.value["fitted_iv"] == pytest.approx(iv.tolist(), abs=1e-4)
    # total variance of the raw form at the money: a + b * (rho * (0 - m) + sqrt(m^2 + sigma^2))
    manual = P0["a"] + P0["b"] * (P0["rho"] * (0 - P0["m"]) + math.sqrt(P0["m"] ** 2 + P0["sigma"] ** 2))
    assert surface.total_variance(0.0, P0) == pytest.approx(manual, abs=1e-15)
    assert surface.total_variance(0.0, P0) == pytest.approx(_lib.ft_svi.get_svi_total_variance(0.0, **P0), abs=1e-12)
    assert np.asarray(_lib.ft_svi.get_svi_implied_volatility(k, t, **res.value["params"])) == pytest.approx(res.value["fitted_iv"], abs=1e-10)
    # bad points are dropped with a warning; too few points, a bad time or NaN give None
    noisy = call("options.svi", log_moneyness=k.tolist() + [float("nan")], implied_vol=iv.tolist() + [0.2], time_to_expiration=t)
    assert noisy.value is not None and any("dropped 1" in w for w in noisy.warnings)
    assert_empty(call("options.svi", log_moneyness=[0.0, 0.1], implied_vol=[0.2, 0.2], time_to_expiration=t), "at least 5")
    assert_empty(call("options.svi", log_moneyness=[], implied_vol=[], time_to_expiration=t), "at least 5")
    assert_empty(call("options.svi", log_moneyness=k.tolist(), implied_vol=[float("nan")] * 25, time_to_expiration=t), "at least 5")
    assert_empty(call("options.svi", log_moneyness=k.tolist(), implied_vol=iv.tolist(), time_to_expiration=0.0), "positive")
    with pytest.raises(BadInput):
        call("options.svi", log_moneyness=k.tolist(), implied_vol=iv.tolist()[:-1], time_to_expiration=t)
    with pytest.raises(BadInput):
        call("options.svi", log_moneyness="0.1", implied_vol=iv.tolist(), time_to_expiration=t)
    with pytest.raises(BadInput):
        call("options.svi", log_moneyness=["a"] * 6, implied_vol=iv.tolist()[:6], time_to_expiration=t)
    assert "FT-038" in piece_ids("options.svi")


def test_static_arbitrage_check_flags_a_bad_smile_FT_038():
    assert surface.butterfly_check(P0)["butterfly_free"] is True
    # hand value: a smile with a negative minimum variance, and one with a very steep wing, break the density
    assert surface.butterfly_check({"a": -0.04, "b": 0.4, "rho": -0.4, "m": 0.0, "sigma": 0.05})["butterfly_free"] is False
    steep = surface.butterfly_check({"a": 0.0, "b": 1.2, "rho": -0.9, "m": 0.0, "sigma": 0.02})
    assert steep["butterfly_free"] is False and steep["min_g"] < 0
    assert surface.butterfly_check({**P0, "b": 3.0})["wings_ok"] is False        # b * (1 + |rho|) above 4


def test_calendar_arbitrage_FT_038():
    flat = lambda w: {"a": w, "b": 1e-6, "rho": 0.0, "m": 0.0, "sigma": 0.1}  # noqa: E731
    free = call("options.svi_calendar", slices={"1.0": flat(0.03), "2.0": flat(0.04)}).value
    assert free["calendar_free"] is True and free["violations"] == 0
    # hand value: total variance of 0.04 at one year and 0.03 at two years falls with time, which is a calendar arbitrage
    bad = call("options.svi_calendar", slices={"1.0": flat(0.04), "2.0": flat(0.03)}).value
    assert bad["calendar_free"] is False and bad["violations"] > 0
    assert bad["worst_variance_drop"] == pytest.approx(0.01, abs=1e-5)
    assert bad["violating_pairs"] == [{"shorter": 1.0, "longer": 2.0}]
    assert call("options.svi_calendar", slices={"1.0": flat(0.04), "2.0": flat(0.03)}, k_min=-0.1, k_max=0.1).value["violations"] > 0
    assert_empty(call("options.svi_calendar", slices={"1.0": flat(0.04)}), "two expiries")
    assert_empty(call("options.svi_calendar", slices={"1.0": {**flat(0.04), "a": float("nan")}, "2.0": flat(0.05)}), "finite")
    assert_empty(call("options.svi_calendar", slices={"1.0": {**flat(0.04), "rho": 1.0}, "2.0": flat(0.05)}), "|rho| < 1")
    assert_empty(call("options.svi_calendar", slices={"1.0": flat(0.04), "-2.0": flat(0.03)}), "positive")
    assert_empty(call("options.svi_calendar", slices={"1.0": flat(0.04), "2.0": flat(0.03)}, k_min=1.0, k_max=0.0), "k_min")
    with pytest.raises(BadInput):
        call("options.svi_calendar", slices=[1, 2])
    with pytest.raises(BadInput):
        call("options.svi_calendar", slices={"1.0": {"a": 0.1}, "2.0": flat(0.03)})
    with pytest.raises(BadInput):
        call("options.svi_calendar", slices={"soon": flat(0.1), "2.0": flat(0.03)})
    assert "FT-038" in piece_ids("options.svi_calendar")


def test_risk_neutral_density_of_a_flat_smile_is_lognormal_FT_039():
    s, r, q, t, sigma = 100.0, 0.03, 0.01, 0.25, 0.20
    flat = {"a": sigma**2 * t, "b": 1e-9, "rho": 0.0, "m": 0.0, "sigma": 0.1}
    res = call("options.risk_neutral_density", spot=s, rate=r, time_to_expiration=t, dividend_yield=q, svi_params=flat, n_strikes=400, levels=[90.0, 100.0, 110.0])
    v = res.value
    forward = s * math.exp((r - q) * t)
    # hand values: lognormal terminal price, f(K) = pdf(d2) / (K sigma sqrt(T)) and P(S_T < L) = N(-d2(L))
    d2 = lambda x: (math.log(s / x) + (r - q - 0.5 * sigma**2) * t) / (sigma * math.sqrt(t))  # noqa: E731
    cdf = lambda x: 0.5 * math.erfc(-x / math.sqrt(2))  # noqa: E731
    pdf = lambda x: math.exp(-0.5 * x * x) / math.sqrt(2 * math.pi)  # noqa: E731
    strikes, dens = np.array(v["strikes"]), np.array(v["density"])
    for target in (90.0, 100.0, 110.0):
        analytic = pdf(d2(target)) / (target * sigma * math.sqrt(t))
        assert float(np.interp(target, strikes, dens)) == pytest.approx(analytic, rel=2e-3)
    assert v["mass"] == pytest.approx(1.0, abs=2e-4)
    assert v["mean"] == pytest.approx(forward, rel=1e-4)
    assert v["forward"] == pytest.approx(forward, abs=1e-12)
    assert v["std"] == pytest.approx(forward * math.sqrt(math.exp(sigma**2 * t) - 1), rel=2e-3)
    assert v["prob_below_spot"] == pytest.approx(cdf(-d2(s)), abs=2e-3)
    for level in (90.0, 100.0, 110.0):
        assert v["prob_below_levels"][f"{level:g}"] == pytest.approx(cdf(-d2(level)), abs=2e-3)
    assert v["negative_density_points"] == 0
    assert any("tails" in w for w in res.warnings)
    # the library function gives the same grid
    lib = _lib.ft_rnd.get_risk_neutral_density(s, forward, t, r, q, flat, 0.5, 400)
    assert dens == pytest.approx(lib.to_numpy(), abs=1e-12)


def test_risk_neutral_density_from_the_recorded_chain_FT_039(chain):
    t = c.years_between(chain["as_of"], "2027-01-15")
    forward = chain["underlying_price"] * math.exp((chain["rate"] - chain["dividend_yield"]) * t)
    rows = [r for r in chain["contracts"] if r["expiration"] == "2027-01-15" and ((r["type"] == "put") == (r["strike"] < forward))]
    k = [math.log(r["strike"] / forward) for r in rows]
    res = call("options.risk_neutral_density", spot=chain["underlying_price"], rate=chain["rate"], time_to_expiration=t, dividend_yield=chain["dividend_yield"],
               log_moneyness=k, implied_vol=[r["iv"] for r in rows])
    assert res.value["mass"] == pytest.approx(1.0, abs=2e-3) and res.value["negative_density_points"] == 0
    assert res.value["mean"] == pytest.approx(forward, rel=2e-3)
    assert 0.40 < res.value["prob_below_spot"] < 0.50                    # a put skew and a positive drift put less than half below spot
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5), "svi_params")
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, log_moneyness=[0.0] * 3, implied_vol=[0.2] * 3), "at least 5")
    assert_empty(call("options.risk_neutral_density", spot=float("nan"), rate=0.03, time_to_expiration=0.5, svi_params=P0))
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.0, svi_params=P0))
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, svi_params={**P0, "sigma": -0.1}), "sigma > 0")
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, svi_params={**P0, "b": float("inf")}), "finite")
    assert_empty(call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, svi_params=P0, strike_range=1.5), "strike_range")
    with pytest.raises(BadInput):
        call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, svi_params=P0, n_strikes=2001)
    with pytest.raises(BadInput):
        call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, svi_params={"a": 1})
    with pytest.raises(BadInput):
        call("options.risk_neutral_density", spot=100.0, rate=0.03, time_to_expiration=0.5, log_moneyness=[0.0] * 6, implied_vol=[0.2] * 5)
    assert "FT-039" in piece_ids("options.risk_neutral_density")


def test_surface_of_the_recorded_chain_FT_040(chain):
    res = call("options.surface", contracts=chain["contracts"], spot=chain["underlying_price"], rate=chain["rate"], as_of=chain["as_of"],
               dividend_yield=chain["dividend_yield"], query=[{"strike": 590.0, "expiration": "2026-12-18"}, {"strike": 610.0, "expiration": "2027-03-19"},
                                                              {"strike": 590.0, "expiration": "2030-01-01"}])
    v = res.value
    assert [e["expiration"] for e in v["expirations"]] == ["2026-11-27", "2026-12-18", "2027-01-15", "2027-03-19", "2027-06-18"]
    # the chain was recorded from smiles with these at-the-money volatilities (0.15 to 0.17): the fit finds them
    assert [e["atm_vol"] for e in v["expirations"]] == pytest.approx([0.150, 0.155, 0.160, 0.165, 0.170], abs=1e-3)
    assert all(e["rmse_iv"] < 1e-3 and e["butterfly_free"] for e in v["expirations"])
    # the long expiries identify the generating skew (rho = -0.7)
    assert [e["svi_params"]["rho"] for e in v["expirations"][2:]] == pytest.approx([-0.7] * 3, abs=0.03)
    assert v["calendar"]["calendar_free"] is True and v["calendar"]["violations"] == 0
    assert [x["atm_vol"] for x in v["atm_term_structure"]] == [e["atm_vol"] for e in v["expirations"]]
    assert v["queries"][0]["iv"] == pytest.approx(0.155, abs=1e-3)
    assert v["queries"][1]["iv"] == pytest.approx(math.sqrt(surface.total_variance(math.log(610.0 / v["expirations"][3]["forward"]), v["expirations"][3]["svi_params"]) / v["expirations"][3]["time_to_expiration"]), abs=1e-12)
    assert v["queries"][2]["iv"] is None
    # an expired or unreadable expiry is skipped with a warning, not fatal
    rows = chain["contracts"] + [{**r, "expiration": "2020-01-17"} for r in chain["contracts"][:12]]
    skipped = call("options.surface", contracts=rows, spot=chain["underlying_price"], rate=chain["rate"], as_of=chain["as_of"])
    assert skipped.value is not None and any("2020-01-17" in w for w in skipped.warnings) and len(skipped.value["expirations"]) == 5
    # a thin expiry is skipped too
    thin = call("options.surface", contracts=[r for r in chain["contracts"] if r["expiration"] == "2027-01-15"][:4] + [r for r in chain["contracts"] if r["expiration"] == "2027-03-19"],
                spot=chain["underlying_price"], rate=chain["rate"], as_of=chain["as_of"])
    assert [e["expiration"] for e in thin.value["expirations"]] == ["2027-03-19"] and any("2027-01-15" in w for w in thin.warnings)
    # a row without iv is inverted from its mid price
    stripped = [{k: v for k, v in r.items() if k != "iv"} for r in chain["contracts"] if r["expiration"] == "2027-06-18"]
    again = call("options.surface", contracts=stripped, spot=chain["underlying_price"], rate=chain["rate"], as_of=chain["as_of"], dividend_yield=chain["dividend_yield"])
    assert again.value["expirations"][0]["atm_vol"] == pytest.approx(0.170, abs=1e-3)
    assert_empty(call("options.surface", contracts=[], spot=100.0, rate=0.03, as_of=chain["as_of"]), "no rows")
    assert_empty(call("options.surface", contracts=[{"strike": 100.0}], spot=100.0, rate=0.03, as_of=chain["as_of"]))
    assert_empty(call("options.surface", contracts=chain["contracts"], spot=float("nan"), rate=0.03, as_of=chain["as_of"]))
    assert_empty(call("options.surface", contracts=chain["contracts"], spot=-5.0, rate=0.03, as_of=chain["as_of"]))
    assert_empty(call("options.surface", contracts=chain["contracts"], spot=590.0, rate=0.03, as_of="not a date"))
    with pytest.raises(BadInput):
        call("options.surface", contracts="chain", spot=100.0, rate=0.03, as_of=chain["as_of"])
    with pytest.raises(BadInput):
        call("options.surface", contracts=[1, 2], spot=100.0, rate=0.03, as_of=chain["as_of"])
    with pytest.raises(BadInput):
        call("options.surface", contracts=chain["contracts"], spot="590", rate=0.03, as_of=chain["as_of"])
    with pytest.raises(BadInput):
        call("options.surface", contracts=chain["contracts"], spot=590.0, rate=0.03, as_of=chain["as_of"], query="590")
    assert "FT-040" in piece_ids("options.surface")
